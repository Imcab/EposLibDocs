PREVIEW = Path(__import__("os").environ["PREVIEW"]) if "PREVIEW" in __import__("os").environ else None


def save(fig, name):
    fig.tight_layout()
    fig.savefig(OUT / f"{name}.svg")
    if PREVIEW:
        fig.savefig(PREVIEW / f"{name}.png")
    plt.close(fig)
    print("wrote", name)


def load(name):
    path = DATA / f"{name}.csv"
    if not path.exists():
        return None
    with path.open() as f:
        rows = list(csv.DictReader(f))
    cols = {k: np.array([float(r[k]) if r[k] and not r[k].startswith("0x") else np.nan
                         for r in rows]) for k in rows[0] if k not in ("statusword", "state", "last_emcy")}
    return cols


