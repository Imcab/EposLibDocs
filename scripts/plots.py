def trapezoid():
    def profile(distance, vmax, acc):
        # distance [rev], vmax [rev/s], acc [rev/s^2]
        t_acc = vmax / acc
        d_acc = 0.5 * acc * t_acc ** 2
        if 2 * d_acc >= distance:            # triangle
            t_acc = np.sqrt(distance / acc)
            vpk = acc * t_acc
            t_total = 2 * t_acc
            t_cruise = 0.0
        else:
            vpk = vmax
            t_cruise = (distance - 2 * d_acc) / vmax
            t_total = 2 * t_acc + t_cruise
        t = np.linspace(0, t_total, 600)
        v = np.where(t < t_acc, acc * t,
                     np.where(t < t_acc + t_cruise, vpk, vpk - acc * (t - t_acc - t_cruise)))
        x = np.concatenate([[0], np.cumsum(v[1:] * np.diff(t))])
        return t, v, x, t_acc, t_cruise

    fig, (a, b) = plt.subplots(2, 1, figsize=(7.5, 4.8), sharex=True)
    for dist, style, label in ((20.0, "-", "20 rev: trapezoid"), (5.0, "--", "5 rev: triangle (v_max never reached)")):
        t, v, x, ta, tc = profile(dist, 1500 / 60, 3000 / 60)
        a.plot(t, v * 60, color=RED if style == "-" else INK, ls=style, lw=1.8, label=label)
        b.plot(t, x, color=RED if style == "-" else INK, ls=style, lw=1.8)
    a.axhline(1500, color=GREY, lw=0.8, ls=":")
    a.text(0.02, 1530, "profile velocity 1500 rpm", color=GREY, fontsize=8)
    a.set_ylabel("velocity [rpm]")
    a.set_title("Trapezoidal profile: v = 1500 rpm, a = d = 3000 rpm/s")
    a.legend(loc="upper right", fontsize=8)
    b.set_ylabel("position [rev]")
    b.set_xlabel("time [s]")
    save(fig, "trapezoid")


def i2t():
    k = np.linspace(1.02, 4.0, 400)
    tp = np.log(k ** 2 / (k ** 2 - 1))
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    ax.plot(k, tp, color=RED, lw=2)
    ax.plot([2.0], [np.log(4 / 3)], "o", color=INK)
    ax.annotate("k = 2  →  t_p = 0.29 τ\n(manual's example: ≈ 0.3 τ)", (2.0, np.log(4 / 3)),
                xytext=(2.4, 0.9), arrowprops=dict(arrowstyle="->", color=INK), fontsize=9)
    ax.set_xlabel("peak current / nominal current   k = I / I_N")
    ax.set_ylabel("allowed time  t_p / τ_th")
    ax.set_ylim(0, 2.5)
    ax.set_title("I²t: how long a current above nominal can last, from cold")
    save(fig, "i2t_peak")

    D = np.linspace(0.02, 1.0, 400)
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    for ratio, style in ((0.1, ":"), (1.0, "-"), (10.0, "--")):
        Ton = D * ratio
        allowed = np.sqrt((1 - np.exp(-ratio)) / (1 - np.exp(-Ton)))
        ax.plot(D * 100, allowed, color=RED if ratio == 1.0 else INK, ls=style, lw=1.8,
                label=f"period T = {ratio:g} τ")
    ex = np.sqrt((1 - np.exp(-1)) / (1 - np.exp(-0.1)))
    ax.plot([10], [ex], "o", color=INK)
    ax.annotate(f"T = τ, 10 % on  →  {ex:.2f}·I_N\n(manual's example: 2.6)", (10, ex),
                xytext=(25, 3.6), arrowprops=dict(arrowstyle="->", color=INK), fontsize=9)
    ax.set_xlabel("on-time ratio  D = T_on / T  [%]")
    ax.set_ylabel("allowed I_on / I_N")
    ax.set_ylim(0.8, 6)
    ax.legend(loc="upper right")
    ax.set_title("I²t in a repeating cycle: current allowed during the on-time")
    save(fig, "i2t_duty")


def torque_speed():
    kt = 0.10479            # N m / A, the motor from the team's test
    kn = 30000 / (np.pi * kt * 1000)   # rpm / V
    i_nom = 9.28
    R = 0.6                 # ohm, illustrative terminal resistance
    fig, ax = plt.subplots(figsize=(7.5, 4.0))
    for U, style in ((11.7, "-"), (24.0, "--")):
        u_eff = 0.9 * U     # the EPOS4 outputs at most 0.9 x VCC
        n0 = kn * u_eff
        stall = kt * u_eff / R
        tau = np.linspace(0, min(stall, 3.0), 200)
        n = n0 - (n0 / stall) * tau
        ax.plot(tau, n, color=RED if U < 20 else INK, ls=style, lw=1.8,
                label=f"voltage limit at {U:g} V supply (no-load ≈ {n0:.0f} rpm)")
    ax.axvline(kt * i_nom, color=GREY, ls=":", lw=1.2)
    ax.text(kt * i_nom + 0.02, 80, f"rated torque\n{kt * i_nom:.3f} N m", color=GREY, fontsize=8)
    ax.set_xlim(0, 1.6)
    ax.set_ylim(0, 2400)
    ax.set_xlabel("torque at the motor shaft [N m]")
    ax.set_ylabel("speed [rpm]")
    ax.set_title("Where a motor can operate: below its voltage line")
    ax.legend(loc="upper right", fontsize=8)
    save(fig, "torque_speed")


def bus_load():
    drives = np.arange(1, 13)
    bits = 130e-6
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    for hz, style in ((100, "-"), (200, "--"), (500, ":")):
        load = (1 + 4 * drives) * bits * hz * 100
        ax.plot(drives, load, color=RED if hz == 100 else INK, ls=style, lw=1.8, marker="o", ms=3,
                label=f"SYNC {hz} Hz")
    ax.axhline(50, color=GREY, lw=1, ls="-.")
    ax.text(8.2, 52, "keep the cyclic load below ~50 %", color=GREY, fontsize=8)
    ax.set_ylim(0, 100)
    ax.set_xlabel("drives on the bus (4 synchronous PDOs each)")
    ax.set_ylabel("bus load at 1 Mbit/s [%]")
    ax.set_title("CAN bus load of the cyclic traffic")
    ax.legend(loc="upper left")
    save(fig, "bus_load")


def pi_step():
    # A PI velocity loop on a first-order mechanical plant J dw/dt = T - b w.
    # Closed loop: J s^2 + (b + Kp) s + Ki, so wn = sqrt(Ki / J) and
    # zeta = (b + Kp) / (2 sqrt(Ki J)). Illustrates the gains, not a real motor.
    dt = 2e-5
    t = np.arange(0, 0.12, dt)
    J, b = 2e-5, 1e-6
    ref = 100.0  # rad/s
    cases = []
    for wn, zeta, style, label in ((200, 1.0, "-", "ζ = 1, ωn = 200 rad/s: fast, no overshoot"),
                                   (50, 1.0, "--", "ζ = 1, ωn = 50 rad/s: low gains, slow"),
                                   (400, 0.35, ":", "ζ = 0.35: I gain too high, overshoot")):
        ki = J * wn ** 2
        kp = 2 * zeta * wn * J - b
        w, integ, out = 0.0, 0.0, []
        for _ in t:
            e = ref - w
            integ += e * dt
            torque = kp * e + ki * integ
            w += (torque - b * w) / J * dt
            out.append(w * 60 / (2 * np.pi))
        cases.append((out, style, label))
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    for out, style, label in cases:
        ax.plot(t * 1000, out, color=RED if style == "-" else INK, ls=style, lw=1.8, label=label)
    ax.axhline(ref * 60 / (2 * np.pi), color=GREY, lw=0.8, ls="-.")
    ax.set_xlabel("time [ms]")
    ax.set_ylabel("velocity [rpm]")
    ax.set_title("Velocity loop: step response for three PI tunings (illustrative plant)")
    ax.legend(loc="lower right", fontsize=8)
    save(fig, "pi_step")


